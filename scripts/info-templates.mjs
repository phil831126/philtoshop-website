/**
 * 【控制畫面】無（輔助工具，不會被打包進網站）
 * 【負責功能】info.txt 範本：npm run photos 發現「有照片、但還沒有 info.txt」的作品資料夾時，
 *            會用這裡的範本自動建立一份，你只要打開改文字即可。
 * 【常見修改】想調整範本的說明文字時改這裡。
 * 【注意事項】只會建立「不存在」的 info.txt，絕不覆蓋你已經寫好的檔案。
 */

/**
 * 資料夾名稱 → 預設標題（與 src/data/projects/index.ts 相同規則）
 *   被遺忘之人、Dark Game → 照原樣；morning-window（全小寫加連字號）→ Morning Window
 */
export const titleFromFolder = (name) =>
  /^[a-z0-9]+(?:[-_][a-z0-9]+)*$/.test(name)
    ? name
        .split(/[-_]+/)
        .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
        .join(' ')
    : name.trim()

export function seriesTemplate({ title = '', model = '', ig = '', date = '', description = '', order = '', cover = '' }) {
  return `# ════════════════════════════════════════════
#  這組作品的文字（存檔後網站自動更新）
#  寫法：欄位：內容（冒號全形、半形都可以）
#  「# 」開頭的行是說明，不會出現在網站上
#  照片：這個資料夾裡的照片會依檔名（01、02…）自動排列
#
#  網站上的排列：
#    01 /
#    標題
#    ──
#    模特
#    IG（自動變成連結）
#    日期
#    [10 PHOTOS]
#  沒填的項目不會顯示。
# ════════════════════════════════════════════

# 標題：留空＝直接用「資料夾名稱」（建議：想改名就改資料夾名稱）
#       只有想讓網站顯示和資料夾不同的名稱時才填
#       想自己決定換行位置：分成好幾行寫，網站就照那樣換行（太寬會自動縮小）
標題：${title}

# 模特名字（好幾位可以寫成好幾行）
模特：${model}

# 模特的 Instagram：填 @帳號 就會自動變成連結（也可以貼個人頁網址）
# 好幾個帳號用「、」分開，例如 @model_a、@model_b
IG：${ig}

# 日期：照寫的顯示，例如 2026/05
日期：${date}

# ── 以下選填 ──

# 介紹：顯示在日期下方，一兩句即可；可放連結 [文字](網址)；不需要就留空
介紹：${description}

# 排在第幾組：建議改到分類資料夾的 info.txt「作品順序」一次排好（那裡有列到的話，以那裡為準）
順序：${order}

# Works 總覽的封面：填照片檔名（不用寫 .jpg）；不填＝第一張
封面：${cover}

# 改成「否」＝暫時不顯示在網站上（不是隱私保護，照片檔案仍是公開的）
顯示：是

# 大圖下方的說明：「照片說明 檔名：文字」，需要幾張就寫幾行
# 照片說明 03：Taipei, 2026
`
}
